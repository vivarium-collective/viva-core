"""Oracle generator for viva-core M3 Task 1 — RNG bit-for-bit parity.

Runs numpy's legacy ``RandomState`` (MT19937 + numpy's own per-distribution
algorithms, the randomkit/distributions.c lineage) and emits the exact streams
the native Rust ``rng`` module must reproduce **bit-for-bit**:

  - MT19937 seeding check: ``get_state()`` key[0:3] (validates init_genrand).
  - ``random_sample(N)``  (res53: two 32-bit words -> 53-bit double).
  - ``stochasticRound`` (v2ecoli.library.random.stochasticRound — pure ``rand``).
  - ``poisson(lam)`` for lam in {0, 2.5, 10, 50} and a vector [0, 3, 0, 12]
    (lam<10 -> rk_poisson_mult; lam>=10 -> rk_poisson_ptrs; lam==0 -> 0, no draw;
    vector consumed elementwise in C order on the shared stream).

Floats are emitted as their IEEE-754 little-endian u64 bit pattern so the Rust
test can assert EXACT bit equality (not an epsilon). Run inside the shared
v2ecoli venv (do NOT modify it):

  /Users/eranagmon/code/v2ecoli/.venv/bin/python \
      crates/bigraph-schema-rs/tests/oracle/gen_rng_oracle.py

Copy the printed `// ORACLE ...` literals into tests/rng_parity.rs.
"""

import struct

import numpy as np

from v2ecoli.library.random import stochasticRound


def bits(x: float) -> int:
    """IEEE-754 u64 bit pattern of a Python/numpy float."""
    return struct.unpack("<Q", struct.pack("<d", float(x)))[0]


SEEDS = [0, 1, 42, 12345]
N_SAMPLE = 8
# Fractional vector exercising floor/ceil both ways + an exact integer (frac 0).
FRAC_VEC = [0.0, 0.25, 0.5, 0.75, 1.0, 2.3, 9.99, 100.5]
POISSON_SCALARS = [0.0, 2.5, 10.0, 50.0]
POISSON_VECTOR = [0.0, 3.0, 0.0, 12.0]

print("// ====================================================================")
print("// AUTO-GENERATED by gen_rng_oracle.py — numpy", np.__version__)
print("// numpy legacy RandomState; floats shown as IEEE-754 u64 bit patterns.")
print("// ====================================================================")

for seed in SEEDS:
    print(f"\n// ---- seed = {seed} ----")

    # 1) seeding check: MT19937 key[0:3]
    rs = np.random.RandomState(seed)
    state = rs.get_state()
    key = state[1]
    print(f"// seed {seed}: key[0:3] = [{int(key[0])}, {int(key[1])}, {int(key[2])}]")

    # 2) random_sample(N) — res53
    rs = np.random.RandomState(seed)
    samples = rs.random_sample(N_SAMPLE)
    sb = ", ".join(f"0x{bits(x):016x}" for x in samples)
    print(f"// seed {seed}: random_sample({N_SAMPLE}) bits = [{sb}]")
    sv = ", ".join(repr(float(x)) for x in samples)
    print(f"//   (values: [{sv}])")

    # 3) stochasticRound on FRAC_VEC (fresh state)
    rs = np.random.RandomState(seed)
    rounded = stochasticRound(rs, np.array(FRAC_VEC, dtype=float))
    rr = ", ".join(str(int(x)) for x in rounded)
    print(f"// seed {seed}: stochastic_round({FRAC_VEC}) = [{rr}]")

    # 4) poisson scalars (fresh state each so cases are independent)
    for lam in POISSON_SCALARS:
        rs = np.random.RandomState(seed)
        draws = rs.poisson(lam, size=6)
        dd = ", ".join(str(int(x)) for x in draws)
        print(f"// seed {seed}: poisson(lam={lam}, size=6) = [{dd}]")

    # 5) poisson VECTOR lam (one shared stream, C order)
    rs = np.random.RandomState(seed)
    vdraws = rs.poisson(np.array(POISSON_VECTOR, dtype=float))
    vv = ", ".join(str(int(x)) for x in vdraws)
    print(f"// seed {seed}: poisson(vec={POISSON_VECTOR}) = [{vv}]")

    # 6) interleaving check: random_sample then poisson on the SAME stream,
    #    to prove stream advancement across distribution boundaries.
    rs = np.random.RandomState(seed)
    pre = rs.random_sample(3)
    pois = rs.poisson(7.5, size=4)
    post = rs.random_sample(2)
    pb = ", ".join(f"0x{bits(x):016x}" for x in pre)
    pp = ", ".join(str(int(x)) for x in pois)
    ob = ", ".join(f"0x{bits(x):016x}" for x in post)
    print(f"// seed {seed}: interleave pre_sample(3) bits = [{pb}]")
    print(f"// seed {seed}: interleave poisson(7.5, 4) = [{pp}]")
    print(f"// seed {seed}: interleave post_sample(2) bits = [{ob}]")
